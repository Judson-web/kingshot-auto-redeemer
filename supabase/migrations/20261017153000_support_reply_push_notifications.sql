-- Private, conversation-scoped web-push subscriptions for support replies.
create table if not exists public.kingshot_support_push_subscriptions (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.kingshot_chat_conversations(id) on delete cascade,
  endpoint text not null,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  unique (conversation_id, endpoint)
);
alter table public.kingshot_support_push_subscriptions enable row level security;
revoke all on public.kingshot_support_push_subscriptions from public, anon, authenticated;
grant all on public.kingshot_support_push_subscriptions to service_role;
create index if not exists kingshot_support_push_conversation_idx
  on public.kingshot_support_push_subscriptions(conversation_id, last_seen_at desc);
